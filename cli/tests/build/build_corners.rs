//! More of the build's rarer paths, driven as a user reaches them: a native
//! program reaching an operation only the web has, `buri test` under a libc
//! the link refuses, a runner whose record points outside the output
//! directory, MC/DC over the standard library's built-in operations, a forced
//! run that prepares generators twice, and a tool whose contract names a
//! schema outside the repository.
use crate::harness::*;

const ONE: &str = "export fn one(): Int {\n    1\n}\n";

const SUITE: &str = "from \"//lib/a\" import { one };\n\
                     from \"core/testing/assert\" import * as assert;\n\n\
                     test \"one\" {\n    assert.equal(one(), 1);\n}\n";

const MOUNTS: &str = r#"from "native" import { NativeHost };
from "platform/effect" import { Scope, Ui };
from "ui/node" import * as ui;

struct Graph {}

impl Ui for Graph {
    fn signal<T>(self, initial: T): Int {
        0
    }

    fn read<T>(self, id: Int): T {
        self.read(id)
    }

    fn write<T>(self, id: Int, value: T): () {}

    fn memo<T>(self, compute: fn(Scope) => T): Int {
        0
    }

    fn watch(self, run: fn(Scope) => ()): () {}

    fn schedule(self, millis: Int, run: fn(Self) => ()): Int {
        0
    }

    fn unschedule(self, id: Int): () {}
}

export fn main(host: NativeHost): Result<(), Str> {
    let ctx = context {
        Ui: Graph {},
    };
    ui.mount(ctx, ui.text({ content: .Const("x") }), [])
}
"#;

const LISTS: &str = r#"from "core/testing/assert" import * as assert;

test "lists" {
    let xs: [Int] = [1, 2, 3];
    assert.equal(xs.length(), 3);
    assert.equal(xs.fold(fn(a, b) => a + b, 0), 6);
}
"#;

const NAMES_SCHEMA: &str = r#"{
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "title": "Names",
    "type": "object",
    "properties": {
        "names": { "type": "array", "items": { "type": "string" } }
    },
    "required": ["names"]
}
"#;

const NAMES_TOOL: &str = r#"from "core/tool" import { Generated, GenerateRequest };
from "platform/effect" import { Allocator };
from "//tools/b/json" import * as a;

export fn generate<C: Allocator>(ctx: C, request: GenerateRequest<a.Names>): Generated {
    Generated { modules: [], diagnostics: [], needs: [] }
}
"#;

/// `//lib/a`, with a suite that passes.
fn suite(name: &str) -> Scratch {
    let scratch = Scratch::repo(name);
    scratch.write(
        "lib/a/BUILD.buri",
        "library {\n    test {\n        sources: [\"test/a.buri\"]\n    }\n}\n",
    );
    scratch.write("lib/a/lib.buri", ONE);
    scratch.write("lib/a/test/a.buri", SUITE);
    scratch
}

/// `//tools/b`, whose `json` contract names `type_schema`, and `//lib/y`,
/// generated by it.
fn contract_tool(scratch: &Scratch, type_schema: &str) {
    scratch.write(
        "tools/b/BUILD.buri",
        &format!(
            "tool {{\n    generate {{\n        accepts: [\n            \
             {{ language: \"json\", type_schema: \"{type_schema}\" }},\n        ]\n    }}\n}}\n"
        ),
    );
    scratch.write("tools/b/b.schema.json", NAMES_SCHEMA);
    scratch.write("tools/b/tool.buri", NAMES_TOOL);
    generated(scratch, "lib/y", "y.json", "");
}

/// A library at `package` generated by `//tools/b` from `input`, with `more`
/// in its rule.
fn generated(scratch: &Scratch, package: &str, input: &str, more: &str) {
    scratch.write(
        &format!("{package}/BUILD.buri"),
        &format!(
            "library {{\n    generators: [\n        \
             {{ tool: \"//tools/b\", inputs: [\"{input}\"] }},\n    ]\n{more}}}\n"
        ),
    );
    scratch.write(&format!("{package}/{input}"), "{\"names\": [\"b\"]}\n");
    scratch.write(&format!("{package}/lib.buri"), ONE);
}

/// A native program that brings its own `Ui` and mounts a page reaches an
/// operation no native backend has, and the build names it.
#[test]
fn a_native_program_that_mounts_a_page_is_refused_by_name() {
    if let Some(why) = ci::native_host_gap() {
        ci::skipped("build::build_corners", &why);
        return;
    }
    let scratch = Scratch::repo("corners-mount");
    scratch.write(
        "cmd/a/BUILD.buri",
        "binary {\n    outputs: [\n        { platform: \"native\" },\n    ]\n}\n",
    );
    scratch.write("cmd/a/main.buri", MOUNTS);
    scratch
        .run(&["build", "//cmd/a"])
        .exits(1)
        .says("error: the stencil backend has no implementation of ui_node.mount");
}

/// `BURI_MUSL` only speaks to a Linux link. There, a value that isn't a libc
/// refuses the suite's link; elsewhere the suite runs.
#[test]
fn buri_test_under_a_libc_the_link_refuses_says_why() {
    if let Some(why) = ci::native_host_gap() {
        ci::skipped("build::build_corners", &why);
        return;
    }
    let scratch = suite("corners-musl");
    let run = scratch.run_with_env(&["test", "//lib/a"], &[("BURI_MUSL", "bogus")]);
    if cfg!(target_os = "linux") {
        run.exits(1)
            .says("`BURI_MUSL=bogus` is not a libc this toolchain can be forced to");
    } else {
        run.ok().says("1 passed, 0 failed");
    }
}

/// A record whose runner lies outside the output directory is not started
/// there: the runner is restored from the cache instead, and nothing is
/// written where the record pointed.
#[test]
fn a_runner_recorded_outside_the_output_directory_is_restored() {
    if let Some(why) = ci::native_host_gap() {
        ci::skipped("build::build_corners", &why);
        return;
    }
    let scratch = suite("corners-runner");
    scratch
        .run(&["test", "//lib/a"])
        .ok()
        .says("1 passed, 0 failed");
    let (magic, out) = (&b"buri-test-build-"[..], &b".buri/out"[..]);
    let mut damaged = 0;
    for dir in std::fs::read_dir(scratch.path(".buri/cache"))
        .unwrap()
        .flatten()
    {
        let Ok(entries) = std::fs::read_dir(dir.path()) else {
            continue;
        };
        for entry in entries.flatten() {
            let mut bytes = std::fs::read(entry.path()).unwrap();
            if !bytes.windows(magic.len()).any(|w| w == magic) {
                continue;
            }
            let Some(at) = bytes.windows(out.len()).position(|w| w == out) else {
                continue;
            };
            bytes.splice(at..at + out.len(), b"elsewhere".iter().copied());
            std::fs::write(entry.path(), bytes).unwrap();
            damaged += 1;
        }
    }
    assert_eq!(
        damaged, 1,
        "no record of the runner's place was found to damage"
    );
    // A golden is in the verdict's key and not in the build's.
    scratch.write("lib/a/test/__snapshots__/unused.png", "not a picture\n");
    scratch
        .run_with_env(&["test", "//lib/a"], &[("BURI_PROFILE", "1")])
        .ok()
        .says("1 passed, 0 failed")
        .says("suites restored 1");
    assert!(
        !scratch.path("elsewhere").exists(),
        "a runner was written where the record pointed"
    );
}

/// `BURI_COVERAGE_STD=1` under MC/DC counts the standard library, and a suite
/// that calls its built-in generic operations is counted like any other.
#[test]
fn mcdc_over_the_standard_library_counts_its_built_in_operations() {
    let repo = tests_dir().join("repositories/coverage/mcdc/repo");
    let scratch = Scratch::copy_of("corners-std-mcdc", &repo);
    scratch.edit(
        "lib/d/BUILD.buri",
        "\"test/d.buri\"",
        "\"test/d.buri\", \"test/lists.buri\"",
    );
    scratch.write("lib/d/test/lists.buri", LISTS);
    let args = ["test", "//lib/d", "--coverage=mcdc"];
    let run = scratch.run_with_env(&args, &[("BURI_COVERAGE_STD", "1")]);
    run.ok().says("5 passed, 0 failed");
    let row = run.stdout.lines().any(|l| l.starts_with("  core/list "));
    assert!(row, "no row for core/list:\n{}", indent(&run.stdout));
}

/// `--force` runs a rule's generators again when the lint, which
/// `check_during_build` runs inside `buri test`, prepares every rule a second
/// time in the same command.
#[test]
fn a_forced_test_that_lints_prepares_every_generator_again() {
    let scratch = Scratch::repo("corners-force-generators");
    scratch.write("REPO.buri", "lint {\n    check_during_build: true\n}\n");
    contract_tool(&scratch, "b.schema.json");
    generated(
        &scratch,
        "lib/a",
        "a.json",
        "\n    test {\n        sources: [\"test/a.buri\"]\n    }\n",
    );
    scratch.write("lib/a/test/a.buri", SUITE);
    // A file no rule lists makes the lint want every rule's generated code.
    scratch.write("lib/a/stray.json", "{}\n");
    scratch
        .run(&["test", "--force", "//lib/a"])
        .ok()
        .says("1 passed, 0 failed")
        .says("lib/a/stray.json");
}

/// A tool whose contract names a schema outside the repository does not
/// build, and a library generated by it says why.
#[test]
fn a_tool_whose_contract_is_outside_the_repository_fails_its_library() {
    let scratch = Scratch::repo("corners-contract-outside");
    contract_tool(&scratch, "https://example.com/b.schema.json");
    scratch.run(&["build", "//lib/y"]).exits(1).says(
        "error: `https://example.com/b.schema.json` is not a file in this repository \
         [schema-outside-repository]",
    );
}
