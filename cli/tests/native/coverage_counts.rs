//! `buri test --coverage` counts what a run did, checked against counts nothing
//! measured: generated packages whose every line, branch and condition has a
//! count known by construction (`generator.rs` lists the shapes).
//!
//! The corpus is checked in at `cli/tests/coverage_counts/`: the repository,
//! and what `--coverage` and `--coverage=mcdc` must print and write for it. It
//! regenerates from [`SEED`]:
//!
//! ```text
//! BURI_BLESS=1 cargo test -p buri --test native coverage_counts::the_checked_in_corpus_is_up_to_date
//! ```
//!
//! Each backend built in, and JavaScript, must report exactly the expected
//! counts, so they agree with each other too. A failing test's report can come
//! in any order, so it's compared sorted; everything else byte for byte.

use std::path::{Path, PathBuf};
use std::process::Command;

mod generator;

/// The seed the checked-in corpus was drawn from.
const SEED: u64 = 0x636f_7665_7261_6765;

/// How many packages the corpus has.
const PACKAGES: usize = 12;

/// Each mode, and the name of its expected files.
const MODES: [(&str, &str); 2] = [("--coverage", "branch"), ("--coverage=mcdc", "mcdc")];

fn corpus() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/coverage_counts")
}

/// Every file of the corpus, by path from [`corpus`].
fn generated() -> Vec<(String, String)> {
    let packages = generator::packages(SEED, PACKAGES);
    let mut files = vec![("repo/REPO.buri".to_string(), "# Generated by cli/tests/native/coverage_counts.rs.\n".to_string())];
    for p in &packages {
        files.extend(p.files.iter().map(|(path, text)| (format!("repo/{path}"), text.clone())));
    }
    for (mode, (_, name)) in MODES.iter().enumerate() {
        let mcdc = mode == 1;
        let mut lcov = String::new();
        let mut rows = Vec::new();
        // In the report's order: by file.
        let mut counted: Vec<&(String, [generator::Expect; 2])> = packages.iter().flat_map(|p| &p.counted).collect();
        counted.sort_by(|a, b| a.0.cmp(&b.0));
        for (file, expect) in counted {
            let (text, row) = generator::lcov(file, &expect[mode], mcdc);
            lcov.push_str(&text);
            rows.push((file.clone(), row));
        }
        let mut failures: Vec<&String> = packages.iter().flat_map(|p| &p.failures).collect();
        failures.sort();
        let mut out: String = failures.iter().map(|f| format!("{f}\n")).collect();
        let passed: usize = packages.iter().map(|p| p.passed).sum();
        out.push_str(&format!("{passed} passed, {} failed, 0 skipped\n", failures.len()));
        out.push_str(&generator::summary(&rows, mcdc));
        files.push((format!("expected/{name}.info"), lcov));
        files.push((format!("expected/{name}.txt"), out));
    }
    files
}

fn buri() -> Command {
    Command::new(env!("CARGO_BIN_EXE_buri"))
}

#[test]
fn the_checked_in_corpus_is_up_to_date() {
    let want = generated();
    let dir = corpus();
    if std::env::var("BURI_BLESS").is_ok_and(|v| v == "1") {
        let _ = std::fs::remove_dir_all(&dir);
        for (path, text) in &want {
            let path = dir.join(path);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, text).unwrap();
        }
    }
    let mut have = Vec::new();
    list(&dir, &dir, &mut have);
    have.sort();
    let mut names: Vec<String> = want.iter().map(|(n, _)| n.clone()).collect();
    names.sort();
    assert_eq!(have, names, "the files in {} are not the generator's; run it with BURI_BLESS=1", dir.display());
    for (path, text) in &want {
        let on_disk = std::fs::read_to_string(dir.join(path)).unwrap();
        assert!(on_disk == *text, "{path} differs from what the generator writes for seed {SEED:#x}; run it with BURI_BLESS=1");
    }
    // The layout the counts assume is the one the formatter keeps.
    let ran = crate::shared::ran_command(buri().current_dir(dir.join("repo")).args(["format", "--check"]));
    assert_eq!(ran.status, 0, "the generated sources aren't formatted:\n{}{}", ran.stdout, ran.stderr);
}

fn list(root: &Path, dir: &Path, out: &mut Vec<String>) {
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.file_name().is_some_and(|n| n == ".buri") {
            continue;
        }
        if path.is_dir() {
            list(root, &path, out);
        } else {
            out.push(path.strip_prefix(root).unwrap().to_string_lossy().into_owned());
        }
    }
}

/// A fresh copy of the corpus's repository.
fn repository(name: &str) -> PathBuf {
    let repo = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("coverage-counts-{}", std::process::id())).join(name);
    let _ = std::fs::remove_dir_all(&repo);
    let mut files = Vec::new();
    let from = corpus().join("repo");
    list(&from, &from, &mut files);
    for f in files {
        let to = repo.join(&f);
        std::fs::create_dir_all(to.parent().unwrap()).unwrap();
        std::fs::copy(from.join(&f), to).unwrap();
    }
    repo
}

/// What one run printed and wrote: its stdout with times taken out, and the
/// lcov.
fn covered(repo: &Path, mode: &str, flags: &[&str]) -> (i32, String, String) {
    let ran = crate::shared::ran_command(buri().current_dir(repo).args(["test", "//...", mode]).args(flags));
    let lcov = std::fs::read_to_string(repo.join(".buri/coverage/lcov.info"))
        .unwrap_or_else(|e| panic!("{mode} {flags:?} wrote no lcov ({e}):\n{}{}", ran.stdout, ran.stderr));
    (ran.status, untimed(&ran.stdout), lcov)
}

/// `stdout` without the run's elapsed time.
fn untimed(stdout: &str) -> String {
    stdout
        .lines()
        .map(|l| match l.rsplit_once(" skipped (") {
            Some((head, _)) if l.ends_with("s)") => format!("{head} skipped\n"),
            _ => format!("{l}\n"),
        })
        .collect()
}

/// `stdout` with each failing test's report sorted.
fn sorted(stdout: &str) -> String {
    let mut blocks: Vec<String> = Vec::new();
    let mut rest = String::new();
    let mut in_failures = true;
    for line in stdout.lines() {
        if in_failures && line.starts_with("FAIL ") {
            blocks.push(format!("{line}\n"));
        } else if in_failures && line.starts_with("  ") && !blocks.is_empty() {
            blocks.last_mut().unwrap().push_str(&format!("{line}\n"));
        } else if in_failures && line.is_empty() {
            continue;
        } else {
            in_failures = false;
            rest.push_str(&format!("{line}\n"));
        }
    }
    blocks.sort();
    blocks.concat() + &rest
}

/// Both modes on one backend, against the expected files.
fn counts(backend: &str, flags: &[&str]) {
    let repo = repository(backend);
    for (mode, name) in MODES {
        let (status, stdout, lcov) = covered(&repo, mode, flags);
        let expected = corpus().join("expected");
        let want = std::fs::read_to_string(expected.join(format!("{name}.info"))).unwrap();
        let printed = std::fs::read_to_string(expected.join(format!("{name}.txt"))).unwrap();
        let fails = !printed.starts_with(|c: char| c.is_ascii_digit());
        assert_eq!(status, i32::from(fails), "{backend} {mode}:\n{stdout}");
        assert_lcov(&format!("{backend} {mode}"), &lcov, &want);
        assert_eq!(sorted(&stdout), printed, "{backend} {mode} printed another report");
    }
}

/// `lcov` against `want`, naming the first record that differs.
fn assert_lcov(what: &str, lcov: &str, want: &str) {
    if lcov == want {
        return;
    }
    let (got, wanted): (Vec<&str>, Vec<&str>) = (lcov.lines().collect(), want.lines().collect());
    let file = |lines: &[&str], at: usize| {
        lines[..at].iter().rev().find(|l| l.starts_with("SF:")).map_or(String::new(), |l| l.to_string())
    };
    let at = got.iter().zip(&wanted).position(|(a, b)| a != b).unwrap_or(got.len().min(wanted.len()));
    panic!(
        "{what}: the lcov differs at line {} ({}): got {:?}, expected {:?}",
        at + 1,
        file(&wanted, at.min(wanted.len())),
        got.get(at),
        wanted.get(at)
    );
}

#[test]
fn counts_on_javascript() {
    counts("javascript", &["--output=js"]);
}

#[cfg(feature = "backend-stencil")]
#[test]
fn counts_on_stencil() {
    if !crate::stencil::supported() {
        return;
    }
    counts("stencil", &[]);
}

#[cfg(feature = "backend-llvm")]
#[test]
fn counts_on_llvm() {
    if let Some(why) = crate::llvm::can_execute() {
        crate::ci::skipped("llvm", why);
        return;
    }
    counts("llvm", &["--release"]);
}

/// The report, verdicts and lcov alike, is the same bytes on every run, apart
/// from the time: each run reads its counts in another order and hashes with
/// another seed.
#[test]
fn the_report_is_the_same_every_run() {
    let repo = repository("again");
    for (mode, _) in MODES {
        let first = covered(&repo, mode, &["--output=js"]);
        for _ in 0..2 {
            let again = covered(&repo, mode, &["--output=js"]);
            assert_eq!(again.1, first.1, "{mode}: the summary changed between runs");
            assert_eq!(again.2, first.2, "{mode}: the lcov changed between runs");
        }
    }
}
