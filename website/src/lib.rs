//! The documentation site.
//!
//! `cli/src/docs/**` and the repository README, rendered to static HTML with
//! no dependency, no build step, and no highlighter in the browser. One
//! command builds it and one flag checks it:
//!
//! ```text
//! cargo run -p website                 # into target/docs-site
//! cargo run -p website -- serve        # and read it on localhost
//! cargo run -p website -- --check      # every link it wrote, followed
//! ```
//!
//! Nothing here writes into the checked-out tree. The output goes under
//! `target/`, which the repository already ignores, and the documentation is
//! read and never modified — the pages are the maintainer's, and a generator
//! that edited them would be a second author.
#![allow(
    clippy::print_stdout,
    clippy::print_stderr,
    reason = "what was written, and why it could not be, is this command's \
              own output; there is no diagnostic session to route it through"
)]

